-- 1. Service history
WITH jobs AS (
  SELECT j.*, v.id AS vehicle_id, v.user_id, v.reg AS crm_reg,
         '[From mileage sheet] ' || j.description AS note
  FROM sheet_jobs j
  JOIN public.vehicles v ON upper(regexp_replace(v.reg, '\s+', '', 'g')) = j.reg
), added AS (
  INSERT INTO public.service_records (user_id, vehicle_id, reg, service_type, service_date, mileage, cost, garage, notes)
  SELECT j.user_id, j.vehicle_id, j.crm_reg, j.service_type, j.service_date, j.mileage, 0, NULL, j.note
  FROM jobs j
  WHERE NOT EXISTS (
    SELECT 1 FROM public.service_records s
    WHERE s.vehicle_id = j.vehicle_id AND s.service_date = j.service_date
      AND coalesce(s.service_type, '') = j.service_type AND coalesce(s.notes, '') = j.note
  )
  RETURNING reg
)
INSERT INTO public.service_import_report
  SELECT 'service jobs added', upper(regexp_replace(reg, '\s+', '', 'g')), count(*)::text || ' job(s)' FROM added GROUP BY reg;

-- 2 + 3. Mileage and next service
WITH upd AS (
  UPDATE public.vehicles v SET
    current_mileage = GREATEST(coalesce(v.current_mileage, 0), coalesce(c.latest_mileage, 0)),
    next_service_mileage = coalesce(c.next_service_mileage, v.next_service_mileage)
  FROM sheet_cars c
  WHERE upper(regexp_replace(v.reg, '\s+', '', 'g')) = c.reg
    AND (coalesce(c.latest_mileage, 0) > coalesce(v.current_mileage, 0)
         OR c.next_service_mileage IS DISTINCT FROM v.next_service_mileage AND c.next_service_mileage IS NOT NULL)
  RETURNING v.reg, v.current_mileage, v.next_service_mileage
)
INSERT INTO public.service_import_report
  SELECT 'mileage updated', upper(regexp_replace(reg, '\s+', '', 'g')),
         current_mileage::text || ' mi' || coalesce(', next service at ' || next_service_mileage::text, '') FROM upd;

-- 4. Driver starting mileage (only where none is recorded)
WITH upd AS (
  UPDATE public.driver_tracks d SET start_mileage = c.hire_mileage,
    current_mileage = GREATEST(coalesce(d.current_mileage, 0), coalesce(c.latest_mileage, c.hire_mileage, 0))
  FROM sheet_cars c
  WHERE upper(regexp_replace(d.reg, '\s+', '', 'g')) = c.reg
    AND d.deleted_at IS NULL AND coalesce(d.active, true)
    AND coalesce(d.start_mileage, 0) = 0 AND c.hire_mileage IS NOT NULL
  RETURNING d.reg, d.driver_name, d.start_mileage
)
INSERT INTO public.service_import_report
  SELECT 'driver start mileage', upper(regexp_replace(reg, '\s+', '', 'g')), driver_name || ': ' || start_mileage::text || ' mi (on hire day)' FROM upd;

